/* Wrestler-rating context for the map cards: for every (season, class, level, district) group of tournament entrants,
   the best and summed season ratings, the count, and a 10-point histogram, so the app can compute Best / Avg / 5th
   percentile for any season range and any State / Region / District scope without loading every bracket.
   In:  data/difficulty/wrestler_seasons.csv (one row per wrestler per tournament, with his season rating)
   Out: overtime/wstats.js  →  window.WR_WSTATS = { bin: 10, g: { "year|cls|lvl|district": [max, sum, n, "bin:count,..."] } }
   lvl: d = district, r = regional, s = state. A wrestler counts once per group even if he wrestled two brackets. */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const lines = fs.readFileSync(path.join(ROOT, 'data/difficulty/wrestler_seasons.csv'), 'utf8').split('\n');
const H = lines[0].split(','), ix = (k) => H.indexOf(k);
const I = { level: ix('level'), t: ix('tournament'), year: ix('year'), cls: ix('cls'), school: ix('school'), key: ix('key'), season: ix('season') };
const rows = [];
for (let i = 1; i < lines.length; i++) {
  const L = lines[i]; if (!L) continue;
  const c = L.split(','); if (c.length < H.length) continue;   // rows with quoted commas are rare; skip them
  const v = +c[I.season]; if (!v) continue;
  rows.push({ lvl: c[I.level], t: c[I.t], year: +c[I.year], cls: c[I.cls], school: c[I.school], key: c[I.key], v });
}
const unitDistrict = (t) => { const m = /^\d{4}_D(\d{1,2})(?:_|$)/.exec(t); return m ? +m[1] : null; };   // D11, D1_AAA_North; not D1-12 / D4-9
// the wrestler's district in a season: his own district bracket; else his school's usual district
const byKY = new Map(), schoolVotes = new Map();
rows.forEach((r) => { if (r.lvl !== 'district') return; const d = unitDistrict(r.t); if (!d) return; byKY.set(r.key + '|' + r.year, d); const m = schoolVotes.get(r.school) || {}; m[d] = (m[d] || 0) + 1; schoolVotes.set(r.school, m); });
const schoolD = new Map(); schoolVotes.forEach((m, s) => schoolD.set(s, +Object.entries(m).sort((a, b) => b[1] - a[1])[0][0]));
const L1 = { district: 'd', regional: 'r', state: 's' };
const G = new Map(), seen = new Set(); let skipped = 0;
rows.forEach((r) => {
  const d = byKY.get(r.key + '|' + r.year) || (r.lvl === 'district' && unitDistrict(r.t)) || schoolD.get(r.school);
  if (!d) { skipped++; return; }
  const k = `${r.year}|${r.cls}|${L1[r.lvl]}|${d}`, sk = k + '|' + r.key; if (seen.has(sk)) return; seen.add(sk);
  let g = G.get(k); if (!g) { g = { max: 0, sum: 0, n: 0, h: new Map() }; G.set(k, g); }
  g.max = Math.max(g.max, r.v); g.sum += r.v; g.n++; const b = Math.floor(r.v / 10); g.h.set(b, (g.h.get(b) || 0) + 1);
});
const out = { bin: 10, g: {} };
G.forEach((g, k) => { out.g[k] = [Math.round(g.max), Math.round(g.sum), g.n, Array.from(g.h.entries()).sort((a, b) => a[0] - b[0]).map(([b, c]) => b + ':' + c).join(',')]; });
fs.writeFileSync(path.join(ROOT, 'overtime/wstats.js'), '/* generated by tools/build_wstats.js */\nwindow.WR_WSTATS=' + JSON.stringify(out) + ';\n');
console.log(`groups ${G.size}, wrestler-entries ${seen.size}, skipped (no district) ${skipped}, size ${(fs.statSync(path.join(ROOT, 'overtime/wstats.js')).size / 1e6).toFixed(2)} MB`);
