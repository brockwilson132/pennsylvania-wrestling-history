/* Builds overtime/missing.js from data/sources/missing_results.csv (tools/parse_postseason.py): the tournaments and
   seasons the bracket archive itself marks as incomplete. Compact: t = tournaments [name, level, cls], m = messages,
   r = [district, tournament index, year, message index]. State and regional entries repeat on every district page that
   feeds them in the source, so they are kept once per district here and de-duplicated in the app. */
const fs = require('fs'), path = require('path');
const csv = fs.readFileSync(path.join(__dirname, '..', 'data', 'sources', 'missing_results.csv'), 'utf8').trim().split(/\r?\n/).slice(1);
const T = [], TI = new Map(), M = [], MI = new Map(), R = [];
const idx = (arr, map, key, val) => { if (!map.has(key)) { map.set(key, arr.length); arr.push(val); } return map.get(key); };
csv.forEach((ln) => {
  const m = ln.match(/^(\d+),([^,]+),(.+),(AAA|AA|single),(\d{4}),(.+)$/);
  if (!m) throw new Error('bad row: ' + ln);
  const [, d, level, name, cls, year, msg] = m;
  const t = idx(T, TI, name + '|' + level + '|' + cls, [name.replace(/^"|"$/g, ''), level, cls]);
  R.push([+d, t, +year, idx(M, MI, msg, msg.replace(/^"|"$/g, ''))]);
});
fs.writeFileSync(path.join(__dirname, '..', 'overtime', 'missing.js'), `/* generated by tools/build_missing.js: results the bracket archive marks as missing */\nwindow.WR_MISSING=${JSON.stringify({ t: T, m: M, r: R })};\n`);
console.log('missing rows', R.length, 'tournaments', T.length, 'messages', M.length, 'unique tournament-seasons', new Set(R.map((r) => r[1] + '|' + r[2])).size);
