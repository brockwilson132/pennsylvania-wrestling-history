/* Icon geometry for the filter bar: the real PA outline, its five regions and twelve districts, simplified to a
 * 26-unit icon box (24 wide). Region membership is the current one (last 5 seasons, both classes). Writes overtime/icongeo.js.
 *   node tools/build_icons.js */
'use strict';
const vm = require('vm'), fs = require('fs'), path = require('path');
const OV = path.join(__dirname, '..', 'overtime');
const D3 = ['/home/claude/almanac/node_modules/d3/dist/d3.min.js', path.join(__dirname, '..', 'node_modules/d3/dist/d3.min.js')].find((p) => fs.existsSync(p));
const ctx = { console, Math, Date, JSON, Map, Set, Array, Object, String, Number, Promise, RegExp, Error, localStorage: { getItem: () => null, setItem: () => {} } };
ctx.window = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(D3, 'utf8'), ctx);
const html = fs.readFileSync(path.join(OV, 'index.html'), 'utf8');
require('./app_scripts')(html).filter((f) => !/^https?:|icongeo/.test(f) && !/components|pages|main|units\.js$|maps/.test(f) || f === 'units.js')
  .forEach((f) => vm.runInContext(fs.readFileSync(path.join(OV, f), 'utf8'), ctx, { filename: f }));
const OT = ctx.OT, M = ctx.PA_MAP, T = ctx.topojson, d3 = ctx.d3;
OT.setCls('ALL'); OT.setWin({ mode: '5' });
const FIVE = ['NE', 'NW', 'SC', 'SE', 'SW'];
const votes = {}; FIVE.forEach((g) => OT.regionMembers(g).forEach((m) => { const n = (m.span.match(/\d{4}/g) || []).length; (votes[m.d] = votes[m.d] || []).push([g, m.n || n]); }));
const of = {}; Object.entries(votes).forEach(([d, v]) => { of[d] = v.sort((a, b) => b[1] - a[1])[0][0]; }); delete of[8];
/* icon box: map 1000×560 → 24 wide, centred in 26 */
const K = 24 / M.w, OX = 1, OY = (26 - M.h * K) / 2;
const proj = d3.geoMercator().scale(M.proj.scale * K).translate([M.proj.translate[0] * K + OX, M.proj.translate[1] * K + OY]);
const gp = d3.geoPath(proj);
/* Douglas–Peucker on each ring */
const dp = (pts, eps) => { if (pts.length < 3) return pts; let mx = 0, ix = 0; const [a, b] = [pts[0], pts[pts.length - 1]]; const dx = b[0] - a[0], dy = b[1] - a[1], L = Math.hypot(dx, dy) || 1;
  for (let i = 1; i < pts.length - 1; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + b[0] * a[1] - b[1] * a[0]) / L; if (d > mx) { mx = d; ix = i; } }
  return mx > eps ? dp(pts.slice(0, ix + 1), eps).slice(0, -1).concat(dp(pts.slice(ix), eps)) : [a, b]; };
const simp = (d, eps = 0.18) => d.split(/(?=M)/).map((sub) => { const pts = Array.from(sub.matchAll(/(-?[\d.]+),(-?[\d.]+)/g)).map((m) => [+m[1], +m[2]]); if (pts.length < 3) return '';
  const s = dp(pts, eps); if (s.length < 3) return ''; const area = Math.abs(d3.polygonArea(s)); if (area < 0.5) return ''; return 'M' + s.map((p) => p[0].toFixed(1) + ',' + p[1].toFixed(1)).join('L') + 'Z'; }).join('');
const geoms = (ds) => M.topo.objects.c.geometries.filter((g) => ds.includes(g.properties.d));
const all = d3.range(1, 13);
const out = { outline: simp(gp(T.merge(M.topo, geoms(all))), 0.15), d: {}, r: {}, of };
all.forEach((d) => { const g = geoms([d]); if (g.length) out.d[d] = simp(gp(T.merge(M.topo, g)), 0.2); });
FIVE.forEach((g) => { const ds = Object.keys(of).map(Number).filter((d) => of[d] === g); const gs = geoms(ds); if (gs.length) out.r[g] = simp(gp(T.merge(M.topo, gs)), 0.2); });
fs.writeFileSync(path.join(OV, 'icongeo.js'), '/* generated by tools/build_icons.js */\nwindow.OT_ICONGEO=' + JSON.stringify(out) + ';\n');
console.log('of', JSON.stringify(of), 'bytes', JSON.stringify(out).length, 'outline pts', (out.outline.match(/L/g) || []).length);
