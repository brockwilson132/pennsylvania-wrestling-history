#!/usr/bin/env python3
"""Turn a school logo image into a site logo.

    python3 tools/make_logo.py "Nazareth" path/to/logo.jpg

Removes a plain background (flood fill from the corners), trims to the mark,
centers it on a transparent square, saves site/logos/<school-slug>.png at 160 px,
and rewrites site/logos/manifest.js. Only someone who can push to the repo can
change the site's logos.
"""
import json, os, re, sys, unicodedata
from collections import deque
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'site', 'logos')

def slug(s):
    s = unicodedata.normalize('NFKD', s).lower()
    return re.sub(r'^-|-$', '', re.sub(r'[^a-z0-9]+', '-', s))

def knock_out(im, tol=38):
    im = im.convert('RGBA'); w, h = im.size; px = im.load()
    seen = bytearray(w * h); q = deque()
    for x, y in [(0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)]:
        q.append((x, y))
    ref = [px[x, y] for x, y in list(q)]
    def near(c):
        if c[3] < 20: return True
        return any(abs(c[0] - r[0]) + abs(c[1] - r[1]) + abs(c[2] - r[2]) <= tol for r in ref if r[3] >= 20)
    while q:
        x, y = q.popleft(); i = y * w + x
        if seen[i]: continue
        seen[i] = 1
        if not near(px[x, y]): continue
        px[x, y] = (0, 0, 0, 0)
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h and not seen[ny * w + nx]: q.append((nx, ny))
    return im

def make(school, src, size=160):
    im = knock_out(Image.open(src))
    box = im.getbbox() or (0, 0, im.size[0], im.size[1])
    im = im.crop(box); side = max(im.size); pad = int(side * 0.04)
    sq = Image.new('RGBA', (side + 2 * pad, side + 2 * pad), (0, 0, 0, 0))
    sq.paste(im, ((sq.size[0] - im.size[0]) // 2, (sq.size[1] - im.size[1]) // 2), im)
    sq = sq.resize((size, size), Image.LANCZOS)
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, slug(school) + '.png'); sq.save(path, optimize=True)
    return path

def manifest():
    files = sorted(f for f in os.listdir(OUT) if f.endswith('.png'))
    data = {f[:-4]: 'logos/' + f for f in files}
    with open(os.path.join(OUT, 'manifest.js'), 'w') as fh:
        fh.write('/* generated by tools/make_logo.py: school slug -> logo file */\nwindow.WR_LOGOS = ' + json.dumps(data, indent=1) + ';\n')
    return data

if __name__ == '__main__':
    if len(sys.argv) == 3:
        print('wrote', make(sys.argv[1], sys.argv[2]))
    print('manifest:', ', '.join(manifest()))
